package com.yourname.training.step4;

public class LoopsJava1 {
    public static void main(String[] args){
        for (int i = 1; i < 11; i++){
            if (i % 2 == 0) {
                System.out.println(i + " - Even");
            }
            else {
                System.out.println(i + " - Odd");
            }
        }
    }
}
